"""使用者提供的北科大鐘點表；A～C 對應既有資料格式 a～c。"""


def default_period_times():
    """每次回傳獨立清單，避免操作影響其他查詢。"""
    times = [
        (1, "08:10", "09:00"), (2, "09:10", "10:00"),
        (3, "10:10", "11:00"), (4, "11:10", "12:00"),
        (5, "13:10", "14:00"), (6, "14:10", "15:00"),
        (7, "15:10", "16:00"), (8, "16:10", "17:00"),
        (9, "17:10", "18:00"), ("a", "18:30", "19:20"),
        ("b", "19:20", "20:10"), ("c", "20:20", "21:10"),
    ]
    return [dict(period=period, start=start, end=end) for period, start, end in times]
